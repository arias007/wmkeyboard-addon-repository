# Function words that splitting a phrase ("in vitro") would
# otherwise add to a specialist list.
STOPWORDS = {"de", "del", "la", "el", "en", "in", "y"}


def build():
    words = {}

    def add_tier(terms, start_freq, step):
        freq = start_freq
        for term in terms:
            # One word per line: a multi-word phrase is split into its words,
            # and each one keeps the first frequency it was given.
            for word in term.strip().lower().split():
                if word and word not in STOPWORDS and word not in words:
                    words[word] = freq
                    freq = max(400, freq - step)

    add_tier(t1_terms, 980, 1)
    add_tier(t2_terms, 940, 1)
    add_tier(t3_terms, 890, 1)
    add_tier(t4_terms, 790, 1)
    add_tier(t5_terms, 690, 1)

    sorted_words = sorted(words.items(), key=lambda x: (-x[1], x[0]))

    lines = [
        "# Diccionario médico y clínico para WM Keyboard (langId=es, locale=es-419)",
        "# Español de América Latina: medicamentos genéricos y marcas comunes en México, Colombia y Argentina, enfermedades, anatomía, procedimientos, estudios y especialidades.",
    ]
    for word, freq in sorted_words:
        lines.append(f"{word} {freq}")

    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Successfully generated {OUTPUT_FILE} with {len(sorted_words)} terms.")


